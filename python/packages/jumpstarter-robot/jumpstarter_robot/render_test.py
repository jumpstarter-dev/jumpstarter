def golden_tree() -> DeviceTree:
    tree = tree_of(
        {
            "dut.power": POWER,
            "storage": FLASHER,
            "shell": {"client": SHELL, "methods": ["hello", "build"]},
            "camera": {"client": POWER, "required": False},
        }
    )
    tree.nodes.append(DeviceNode(name="gone", path=["gone"], kind="opaque", reason="not installed here"))
    return tree


class TestRender:
    def test_golden(self, tmp_path):
        text = render_resource(
            golden_tree(),
            source_args={"exporter_config": tmp_path / "configs" / "exporter.yaml", "config": "lab-eu"},
            resource_dir=tmp_path,
        )
        assert text == GOLDEN

    def test_deterministic(self, tmp_path):
        def render():
            return render_resource(
                golden_tree(), source_args={"exporter_config": tmp_path / "e.yaml"}, resource_dir=tmp_path
            )

        assert render() == render()

    def test_prefix_is_the_full_path(self):
        text = render_resource(tree_of({"dut1.power": POWER, "dut2.power": POWER, "storage": FLASHER}))
        assert prefixes(text) == {"dut1.power": "Dut1 Power", "dut2.power": "Dut2 Power", "storage": "Storage"}

    def test_lone_nested_driver_keeps_its_full_path(self):
        # a path nothing else shares is not shortened: the keyword names say where the driver is
        assert prefixes(render_resource(tree_of({"dut.power": POWER, "storage": FLASHER}))) == {
            "dut.power": "Dut Power",
            "storage": "Storage",
        }

    def test_single_composite_root_is_kept(self):
        # the prefix is the same path Call Driver and Open Console take
        text = render_resource(tree_of({"rig.power": POWER, "rig.dut.power": POWER}))
        assert prefixes(text) == {"rig.power": "Rig Power", "rig.dut.power": "Rig Dut Power"}
        assert prefixes(render_resource(tree_of({"rig.power": POWER}))) == {"rig.power": "Rig Power"}

    def test_root_and_nested_drivers_of_one_name(self):
        text = render_resource(tree_of({"power": POWER, "dut.power": POWER, "rack.dut.power": POWER}))
        assert prefixes(text) == {"power": "Power", "dut.power": "Dut Power", "rack.dut.power": "Rack Dut Power"}

    def test_there_is_no_prefix_mode(self):
        for function in (render_resource, plan):
            assert "prefixes" not in inspect.signature(function).parameters

    def test_aliases_override_prefixes(self):
        text = render_resource(tree_of({"dut.power": POWER, "x": POWER}), aliases={"dut.power": "Main Power"})
        assert prefixes(text)["dut.power"] == "Main Power"

    def test_alias_collision_is_an_error(self):
        with pytest.raises(RenderError, match="same prefix"):
            render_resource(tree_of({"a": POWER, "b": POWER}), aliases={"a": "Main", "b": "main"})

    def test_alias_may_take_a_name_no_full_path_uses(self):
        text = render_resource(tree_of({"dut.power": POWER, "a.storage": POWER}), aliases={"dut.power": "Storage"})
        assert prefixes(text) == {"dut.power": "Storage", "a.storage": "A Storage"}

    def test_alias_of_one_driver_leaves_the_others_full(self):
        text = render_resource(tree_of({"dut.power": POWER, "dut.aux": POWER}), aliases={"dut.power": "Board"})
        assert prefixes(text) == {"dut.power": "Board", "dut.aux": "Dut Aux"}

    def test_alias_clash_with_full_path_is_an_error(self):
        with pytest.raises(RenderError, match="ambiguous") as error:
            render_resource(tree_of({"dut.power": POWER, "storage": POWER}), aliases={"dut.power": "Storage"})
        assert "Storage On" in str(error.value)

    @pytest.mark.parametrize(
        "paths",
        [("a_b.c", "a.b_c"), ("a_b", "a.b"), ("dut.serial_port", "dut.serial.port"), ("dut-1.power", "dut_1.power")],
    )
    def test_normalization_clash_of_full_paths_is_an_error(self, paths):
        # different paths, but Robot Framework would read their keyword names as the same
        with pytest.raises(RenderError, match="ambiguous") as error:
            render_resource(tree_of(dict.fromkeys(paths, POWER)))
        message = str(error.value)
        assert all(f"  {path} (prefix " in message for path in paths), message
        assert "aliases" in message and "--alias path=Prefix" in message

    def test_alias_resolves_a_normalization_clash(self):
        text = render_resource(tree_of({"a_b.c": POWER, "a.b_c": POWER}), aliases={"a.b_c": "Other"})
        assert prefixes(text) == {"a_b.c": "A B C", "a.b_c": "Other"}

    def test_clash_with_jumpstarter_keyword(self):
        tree = tree_of({"release": {"client": SHELL, "methods": ["default_session"]}, "x": POWER})
        with pytest.raises(RenderError, match="Jumpstarter library: Release Default Session"):
            render_resource(tree)

    def test_nested_path_does_not_clash_with_jumpstarter_keyword(self):
        tree = tree_of({"x.release": {"client": SHELL, "methods": ["default_session"]}, "y": POWER})
        assert prefixes(render_resource(tree))["x.release"] == "X Release"

    def test_composites_without_keywords_are_skipped(self):
        tree = tree_of({"dut": COMPOSITE, "dut.power": POWER, "z": POWER})
        assert list(prefixes(render_resource(tree))) == ["dut.power", "z"]

    def test_named_session(self):
        text = render_resource(tree_of({"dut.power": POWER, "x": POWER}), session="sim")
        assert "Library    jumpstarter_robot.Session    sim    " in text
        assert text.splitlines()[3].endswith("AS    session.sim")
        assert "session=sim    AS    sim.dut.power" in text

    def test_include_and_exclude(self):
        tree = tree_of({"dut.power": POWER, "dut.ssh": POWER, "sim.can": POWER, "sim.other": POWER})
        text = render_resource(tree, include=["dut.*", "sim.can"], exclude=["*.ssh"])
        assert list(prefixes(text)) == ["dut.power", "sim.can"]

    def test_unknown_client_class(self):
        with pytest.raises(RenderError, match="cannot import its client"):
            render_resource(tree_of({"a": "jumpstarter_robot_missing.client.NoClient", "b": POWER}))

    def test_unnamed_root(self):
        tree = DeviceTree(device_name="D", nodes=[DeviceNode(name="power", path=[], bindings={"python": POWER})])
        (line,) = driver_lines(render_resource(tree))
        assert "Driver    path=${EMPTY}    client=" in line
        assert line.endswith("prefix=Power    session=default    AS    power")


class TestVariables:
    def test_values(self, tmp_path):
        text = render_resource(
            tree_of({"a": POWER}),
            source_args={"selector": "board=rpi4,lab in (eu)", "lease_name": "", "config": tmp_path / "ci.yaml"},
            resource_dir=tmp_path / "suites",
        )
        assert "${JMP_SELECTOR}    board=rpi4,lab in (eu)\n" in text
        assert "${JMP_LEASE_NAME}    ${EMPTY}\n" in text
        assert "${JMP_CLIENT_CONFIG}    ${CURDIR}/../ci.yaml\n" in text
        assert "${JMP_EXPORTER_CONFIG}    ${EMPTY}\n" in text

    def test_secrets_are_refused(self):
        with pytest.raises(RenderError, match="credentials"):
            render_resource(tree_of({"a": POWER}), source_args={"token": "abc"})
        with pytest.raises(RenderError, match="unknown session argument"):
            render_resource(tree_of({"a": POWER}), source_args={"endpoint": "x"})

    @pytest.mark.parametrize(
        "value, cell",
        [
            ("", "${EMPTY}"),
            (None, "${EMPTY}"),
            ("a  b", "a \\ b"),
            ("${X}", "\\${X}"),
            ("# x", "\\# x"),
            ("back\\slash", "back\\\\slash"),
            (" lead", "\\ lead"),
            ("trail ", "trail${SPACE}"),
            ("a   b", "a \\ \\ b"),
            ("a  ", "a${SPACE}${SPACE}"),
            (" ", "${SPACE}"),
        ],
    )
    def test_escape(self, value, cell):
        assert escape(value) == cell

    def test_escaped_values_read_back_unchanged(self, tmp_path):
        values = ["a  b", "a   b", "a    b", "a  ", " ", "  ", " lead", "back\\ ", "# a  ${b}  ", "t\tab"]
        lines = ["*** Variables ***", *(f"${{V{i}}}    {escape(v)}" for i, v in enumerate(values))]
        lines += ["", "*** Test Cases ***"]
        for i, value in enumerate(values):
            # the expected value is hex, so it needs no escaping of its own
            expected = f"${{{{ bytes.fromhex('{value.encode().hex()}').decode() }}}}"
            lines += [f"Value {i}", f"    Should Be Equal    ${{V{i}}}    {expected}"]
        rc, statuses = run_suite(tmp_path, "\n".join(lines) + "\n")
        assert set(statuses.values()) == {"PASS"}, statuses
        assert rc == 0

    def test_named_session_never_defines_the_default_variables(self):
        text = render_resource(tree_of({"a": POWER}), session="android", source_args={"selector": "board=pixel"})
        variables = text.split("*** Variables ***\n")[1]
        assert variables == (
            "${JMP_ANDROID_EXPORTER_CONFIG}    ${EMPTY}\n"
            "${JMP_ANDROID_SELECTOR}    board=pixel\n"
            "${JMP_ANDROID_LEASE_NAME}    ${EMPTY}\n"
            "${JMP_ANDROID_CLIENT_CONFIG}    ${EMPTY}\n"
        )


class TestRoles:
    def tree(self) -> DeviceTree:
        return tree_of(
            {
                "dut1.power": POWER,
                "dut1.console": SERIAL,
                "dut2.power": POWER,
                "dut2.console": SERIAL,
                "storage": FLASHER,
            }
        )

    def test_groups(self):
        groups = find_role_groups(self.tree())
        assert [[n.dotted for n in group] for group in groups] == [["dut1", "dut2"]]

    def test_different_subtrees_are_not_a_group(self):
        tree = tree_of({"dut1.power": POWER, "dut2.power": SERIAL})
        assert find_role_groups(tree) == []

    def test_role_libraries_and_devices(self):
        text = render_resource(self.tree(), roles=True)
        assert driver_lines(text) == [
            f"{DRIVER}storage    client={FLASHER}    prefix=Storage    session=default    AS    storage",
            f"{DRIVER}dut1.power    role=power    client={POWER}    prefix=Power    session=default    AS    power",
            f"{DRIVER}dut1.console    role=console    client={SERIAL}    prefix=Console    session=default"
            + "    AS    console",
        ]
        assert text.endswith("@{DEVICES}    dut1    dut2\n")

    def test_named_session_devices(self):
        text = render_resource(self.tree(), roles=True, session="multi")
        assert text.endswith("@{MULTI_DEVICES}    dut1    dut2\n")
        assert "@{DEVICES}" not in text

    def test_groups_with_a_clashing_role_keep_plain_libraries(self):
        # box1/box2 also have a `power`, but of another class: `Use Device` binds roles by
        # relative path, so they cannot share the dut boards' `power` role library
        tree = tree_of(
            {
                "dut1.power": POWER,
                "dut1.console": SERIAL,
                "dut2.power": POWER,
                "dut2.console": SERIAL,
                "box1.power": SERIAL,
                "box2.power": SERIAL,
            }
        )
        text = render_resource(tree, roles=True)
        assert driver_lines(text) == [
            f"{DRIVER}box1.power    client={SERIAL}    prefix=Box1 Power    session=default    AS    box1.power",
            f"{DRIVER}box2.power    client={SERIAL}    prefix=Box2 Power    session=default    AS    box2.power",
            f"{DRIVER}dut1.power    role=power    client={POWER}    prefix=Power    session=default    AS    power",
            f"{DRIVER}dut1.console    role=console    client={SERIAL}    prefix=Console    session=default"
            + "    AS    console",
        ]
        assert text.endswith("@{DEVICES}    dut1    dut2\n")

    def test_groups_share_an_identical_role(self):
        tree = tree_of(
            {"dut1.power": POWER, "dut1.console": SERIAL, "dut2.power": POWER, "dut2.console": SERIAL,
             "box1.power": POWER, "box2.power": POWER}
        )
        text = render_resource(tree, roles=True)
        assert [line.split("    ")[2] for line in driver_lines(text)] == ["dut1.power", "dut1.console"]
        assert text.endswith("@{DEVICES}    dut1    dut2\n@{DEVICES_2}    box1    box2\n")

    def test_roles_off_keeps_copies(self):
        assert len(driver_lines(render_resource(self.tree()))) == 5
        assert "@{DEVICES}" not in render_resource(self.tree())

    def test_role_alias(self):
        text = render_resource(self.tree(), roles=True, aliases={"power": "Board Power"})
        assert prefixes(text)["power"] == "Board Power"

    def test_role_run_uses_each_device(self, tmp_path):
        tree = tree_of({"dut1.power": POWER, "dut2.power": POWER})
        write_resource(tmp_path / "client.resource", tree, roles=True)
        devices = Composite(children={"dut1": Composite(children={"power": MockPower()}),
                                      "dut2": Composite(children={"power": MockPower()})})
        suite = """\
        *** Settings ***
        Resource    client.resource

        *** Test Cases ***
        Every Device
            ${bound}=    Create List
            FOR    ${dut}    IN    @{DEVICES}
                ${paths}=    Use Device    ${dut}
                Append To List    ${bound}    @{paths}
                Power On
                Power Off
            END
            Should Be Equal    ${bound}    ${{["dut1.power", "dut2.power"]}}

        *** Settings ***
        Library    Collections
        """
        with serve(devices) as client, use_client(client):
            rc, statuses = run_suite(tmp_path, suite)
        assert statuses == {"Every Device": "PASS"}, statuses
        assert rc == 0


class TestWrite:
    def test_writes_only_the_resource(self, tmp_path):
        resource, planned = write_resource(tmp_path / "out" / "client.resource", golden_tree())
        assert resource.read_text().startswith("*** Settings ***")
        assert sorted(p.name for p in resource.parent.iterdir()) == ["client.resource"]
        assert len(planned.imports) == 4

    def test_plan_without_collision_check(self):
        planned = plan(tree_of({"a_b": POWER, "a.b": POWER}), check=False)
        assert [i.prefix for i in planned.imports] == ["A B", "A B"]

    def test_generated_resource_runs_against_a_served_client(self, tmp_path):
        tree = tree_of({"dut.power": POWER, "other": POWER})
        write_resource(tmp_path / "client.resource", tree)
        suite = """\
        *** Settings ***
        Resource    client.resource

        *** Test Cases ***
        Power Keywords
            Dut Power On
            Dut Power Should Be On
            Other Off
            ${name}=    Get Exporter Name
            Should Be Equal    ${name}    test

        Qualified Name
            dut.power.Dut Power Off
        """
        root = Composite(children={"dut": Composite(children={"power": MockPower()}), "other": MockPower()})
        with serve(root) as client, use_client(client):
            rc, statuses = run_suite(tmp_path, suite)
        assert statuses == {"Power Keywords": "PASS", "Qualified Name": "PASS"}, statuses
        assert rc == 0
