def tree_of(nodes: dict, name: str = "Rig") -> DeviceTree:
    return from_toml_nodes(nodes, device_name=name, ref="robot.toml")


def driver_lines(text: str) -> list[str]:
    return [line for line in text.splitlines() if line.startswith("Library    jumpstarter_robot.Driver")]


def prefixes(text: str) -> dict[str, str]:
    found = {}
    for line in driver_lines(text):
        cells = line.split("    ")
        prefix = next(c for c in cells if c.startswith("prefix=")).removeprefix("prefix=")
        found[cells[-1]] = prefix
    return found


def run_suite(directory: Path, suite: str) -> tuple[int, dict[str, str]]:
    path = directory / "suite.robot"
    path.write_text(textwrap.dedent(suite))
    output = directory / "output.xml"
    rc = robot.run(str(path), outputdir=str(directory), output=str(output), report="NONE", log="NONE", console="none")
    statuses = {}
    result = ExecutionResult(str(output))

    def collect(suite):
        for test in suite.tests:
            statuses[test.name] = f"{test.status}: {test.message}" if test.status != "PASS" else "PASS"
        for child in suite.suites:
            collect(child)

    collect(result.suite)
    return rc, statuses


