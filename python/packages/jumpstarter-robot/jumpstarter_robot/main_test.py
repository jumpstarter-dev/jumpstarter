@pytest.mark.parametrize("first", ["default", "b"])
def test_default_and_named_resources_in_one_suite(workdir, leased, first):
    # the default session's selector must neither leak into session b nor be
    # lost when b's resource is imported first
    write(workdir / "other.yaml", EXPORTER.replace("name: mock-rig", "name: other-rig"))
    assert main(["generate", "--selector", "board=rpi4", "-o", "default.resource"]) == EXIT_OK
    assert main(["generate", "--exporter-config", "other.yaml", "--session", "b", "-o", "b.resource"]) == EXIT_OK
    _, calls = leased
    calls.clear()
    order = ["default", "b"] if first == "default" else ["b", "default"]
    rc, tests = run_suite(
        workdir,
        f"""\
        *** Settings ***
        Resource    {order[0]}.resource
        Resource    {order[1]}.resource

        *** Test Cases ***
        Each Session Keeps Its Own Source
            ${{b}}=    Get Exporter Name    session=b
            Should Be Equal    ${{b}}    other-rig
            ${{default}}=    Get Exporter Name    session=default
            Should Be Equal    ${{default}}    rpi4-01
        """,
    )
    assert tests == {"Each Session Keeps Its Own Source": "PASS"}, tests
    assert rc == 0
    assert [(name, kwargs["selector"]) for name, kwargs in calls] == [("default", "board=rpi4")]


def test_two_client_resources_in_one_suite_keep_their_exporters(workdir):
    # Robot keeps the first value of a variable; per-session names stop the
    # second resource from inheriting the first one's exporter config.
    write(workdir / "other.yaml", EXPORTER.replace("name: mock-rig", "name: other-rig"))
    assert main(["generate", "--exporter-config", "exporter.yaml", "--session", "a", "-o", "a.resource"]) == EXIT_OK
    assert main(["generate", "--exporter-config", "other.yaml", "--session", "b", "-o", "b.resource"]) == EXIT_OK
    rc, tests = run_suite(
        workdir,
        """\
        *** Settings ***
        Resource    a.resource
        Resource    b.resource

        *** Test Cases ***
        Each Session Has Its Own Exporter
            ${a}=    Get Exporter Name    session=a
            ${b}=    Get Exporter Name    session=b
            Should Be Equal    ${a}    mock-rig
            Should Be Equal    ${b}    other-rig
        """,
    )
    assert tests == {"Each Session Has Its Own Exporter": "PASS"}, tests
    assert rc == 0


