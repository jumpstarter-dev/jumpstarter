class TestGenerateFromExporterConfig:
    def test_resource_text(self, workdir, capsys):
        assert main(["generate", "--exporter-config", "exporter.yaml"]) == EXIT_OK
        text = (workdir / "client.resource").read_text()
        lines = text.splitlines()
        assert lines[0] == "*** Settings ***"
        assert lines[1].startswith("Documentation    Generated by `jmp robot generate` from ")
        assert "exporter config exporter.yaml (device MockRig, session default)" in lines[1]
        assert lines[2] == "Library    jumpstarter_robot.Jumpstarter    auto_import=False"
        assert lines[3] == (
            "Library    jumpstarter_robot.Session    default    exporter_config=${JMP_EXPORTER_CONFIG}    "
            "selector=${JMP_SELECTOR}    lease_name=${JMP_LEASE_NAME}    config=${JMP_CLIENT_CONFIG}    "
            "AS    session.default"
        )
        assert lines[4:7] == [
            f"Library    jumpstarter_robot.Driver    dut.power    client={POWER}    prefix=Dut Power    "
            + "session=default    AS    dut.power",
            f"Library    jumpstarter_robot.Driver    dut.storage    client={FLASHER}    prefix=Dut Storage    "
            + "session=default    AS    dut.storage",
            f"Library    jumpstarter_robot.Driver    shell    client={SHELL}    prefix=Shell    "
            + "session=default    methods=hello    AS    shell",
        ]
        assert text.endswith(
            "*** Variables ***\n"
            "${JMP_EXPORTER_CONFIG}    ${CURDIR}/exporter.yaml\n"
            "${JMP_SELECTOR}    ${EMPTY}\n"
            "${JMP_LEASE_NAME}    ${EMPTY}\n"
            "${JMP_CLIENT_CONFIG}    ${EMPTY}\n"
        )
        assert not (workdir / "client.tree.json").exists()  # only the resource is written
        assert "default: wrote client.resource (3 driver libraries)\n" in capsys.readouterr().out

    def test_resource_runs_in_local_mode(self, workdir):
        assert main(["generate", "--exporter-config", "exporter.yaml"]) == EXIT_OK
        rc, statuses = run_suite(
            workdir,
            """\
            *** Settings ***
            Resource    client.resource

            *** Test Cases ***
            Power And Storage
                Dut Power On
                Dut Power Should Be On
                ${readings}=    Dut Power Read    max_items=2
                Length Should Be    ${readings}    2
                Dut Storage Dut
                Dut Power Off

            Shell Method
                ${result}=    Shell Hello    world    GREETING=hi
                Should Contain    ${result.stdout}    hello world hi

            Session Is Local
                ${name}=    Get Exporter Name
                Should Be Equal    ${name}    mock-rig
            """,
        )
        assert statuses == {"Power And Storage": "PASS", "Shell Method": "PASS", "Session Is Local": "PASS"}, statuses
        assert rc == 0

    def test_options(self, workdir):
        args = ["generate", "--exporter-config", "exporter.yaml", "-o", "out/dut.resource", "--session", "dut"]
        assert main([*args, "--alias", "shell=Host", "--exclude", "*.storage"]) == EXIT_OK
        text = (workdir / "out" / "dut.resource").read_text()
        assert "prefix=Dut Power    session=dut    AS    dut.dut.power" in text
        assert "prefix=Host    session=dut    methods=hello    AS    dut.shell" in text
        assert "dut.storage" not in text
        # a named session gets its own variables, so two resources in one suite stay apart
        assert "${JMP_DUT_EXPORTER_CONFIG}    ${CURDIR}/../exporter.yaml" in text
        assert "${JMP_DUT_SELECTOR}    ${EMPTY}" in text
        assert "${JMP_SELECTOR}" not in text  # the default session's, which another resource may set

    def test_bad_alias(self, workdir, capsys):
        assert main(["generate", "--exporter-config", "exporter.yaml", "--alias", "nope"]) == EXIT_ERROR
        assert "PATH=PREFIX" in capsys.readouterr().err

    def test_libspec(self, workdir):
        assert main(["generate", "--exporter-config", "exporter.yaml", "--libspec", "specs"]) == EXIT_OK
        specs = sorted(p.name for p in (workdir / "specs").iterdir())
        assert specs == ["dut.power.libspec", "dut.storage.libspec", "shell.libspec"]
        spec = (workdir / "specs" / "dut.power.libspec").read_text()
        assert 'name="Dut Power On"' in spec

    def test_tree_round_trip(self, workdir):
        assert main(["generate", "--exporter-config", "exporter.yaml"]) == EXIT_OK
        first = (workdir / "client.resource").read_text()
        (workdir / "client.tree.json").write_text(from_exporter_config(workdir / "exporter.yaml").to_json())
        assert main(["generate", "--tree", "client.tree.json", "-o", "again.resource"]) == EXIT_OK
        again = (workdir / "again.resource").read_text()

        def drivers(text):
            return [line for line in text.splitlines() if "jumpstarter_robot.Driver" in line]

        assert drivers(again) == drivers(first)
        assert "from exporter config exporter.yaml" in again  # the tree remembers where it came from
        assert "${JMP_EXPORTER_CONFIG}    ${EMPTY}" in again  # but a tree alone does not serve anything


