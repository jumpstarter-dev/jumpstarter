class TestCapture:
    TOML = """\
    # lab clients
    [tool.jumpstarter.client.rpi4]
    selector = "board=rpi4"       # leased at run time
    config = "lab-eu"
    resource = "client-rpi4.resource"
    """

    def test_capture_writes_nodes_and_regenerates(self, workdir, leased):
        project = write(workdir / "robot.toml", self.TOML)
        assert main(["generate", "--capture", "--client", "rpi4"]) == EXIT_OK
        text = project.read_text()
        assert text.startswith(textwrap.dedent(self.TOML))  # comments and order kept
        nodes = tomllib.loads(text)["tool"]["jumpstarter"]["client"]["rpi4"]["nodes"]
        assert nodes == {
            "dut.power": POWER,
            "dut.storage": FLASHER,
            "shell": {"client": SHELL, "methods": ["hello"]},
        }
        _, calls = leased
        assert calls == [
            (
                "rpi4",
                {
                    "config": "lab-eu",
                    "config_dir": workdir.resolve(),
                    "selector": "board=rpi4",
                    "lease_name": None,
                },
            )
        ]
        resource = (workdir / "client-rpi4.resource").read_text()
        assert "methods=hello    AS    rpi4.shell" in resource
        # regenerating from the committed nodes gives the same resource, with no lease
        before = resource
        calls.clear()
        assert main(["generate", "--client", "rpi4"]) == EXIT_OK
        assert (workdir / "client-rpi4.resource").read_text() == before
        assert calls == []

    def test_capture_without_project_creates_robot_toml(self, workdir, leased):
        assert main(["generate", "--capture", "--selector", "board=rpi4", "--session", "lab"]) == EXIT_OK
        loaded = Project.load(workdir / "robot.toml").client("lab")
        assert loaded.selector == "board=rpi4"
        assert loaded.resource == workdir / "client.resource"
        assert loaded.nodes is not None
        assert loaded.nodes["dut.power"] == POWER

    def test_capture_from_describe(self, workdir):
        project = write(workdir / "robot.toml", self.TOML)
        with serve(live_exporter()) as client:
            dump = {"lease": {"name": "l1", "exporter": "rpi4-01"}, "driver_tree": describe_client(client)}
        write(workdir / "describe.json", json.dumps(dump))
        assert main(["generate", "--capture", "--client", "rpi4", "--from", "describe.json"]) == EXIT_OK
        nodes = Project.load(project).client("rpi4").nodes
        assert nodes == {"dut.power": POWER, "dut.storage": FLASHER, "shell": SHELL}

    def test_capture_from_describe_keeps_committed_methods(self, workdir):
        shell = f'"shell" = {{ client = "{SHELL}", methods = ["hello"] }}\n'
        project = write(workdir / "robot.toml", self.TOML + "\n[tool.jumpstarter.client.rpi4.nodes]\n" + shell)
        with serve(live_exporter()) as client:
            write(workdir / "describe.json", json.dumps({"driver_tree": describe_client(client)}))
        assert main(["generate", "--capture", "--client", "rpi4", "--from", "describe.json"]) == EXIT_OK
        nodes = Project.load(project).client("rpi4").nodes
        assert nodes == {"dut.power": POWER, "dut.storage": FLASHER, "shell": {"client": SHELL, "methods": ["hello"]}}
        assert "methods=hello    AS    rpi4.shell" in (workdir / "client-rpi4.resource").read_text()

    @pytest.mark.parametrize("mode", ["--capture", "--check", "--live"])
    def test_jmp_shell_needs_one_client(self, workdir, monkeypatch, capsys, mode):
        # the shell is one exporter: it must not be recorded as (or checked against) every client
        nodes = f'\n[tool.jumpstarter.client.rpi4.nodes]\n"x" = "{POWER}"\n'
        other = nodes.replace("rpi4", "ios")
        ios = '\n[tool.jumpstarter.client.ios]\nselector = "platform=ios"\n'
        write(workdir / "robot.toml", self.TOML + nodes + ios + other)
        before = (workdir / "robot.toml").read_text()
        monkeypatch.setenv(JUMPSTARTER_HOST, "unix:///nowhere")
        assert main(["generate", mode]) == EXIT_ERROR
        assert "name its client with --client (rpi4, ios)" in capsys.readouterr().err
        assert (workdir / "robot.toml").read_text() == before

    def test_capture_inside_jmp_shell(self, workdir, monkeypatch):
        write(workdir / "robot.toml", self.TOML)
        monkeypatch.setenv(JUMPSTARTER_HOST, "unix:///nowhere")
        with serve(live_exporter()) as client:
            shell = lambda name: sessions.Session.from_client(client, name, exporter="shell")  # noqa: E731
