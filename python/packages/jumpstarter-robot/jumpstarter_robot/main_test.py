class TestCheck:
    def project(self, workdir, nodes: str) -> Path:
        return write(
            workdir / "robot.toml",
            f'[tool.jumpstarter.client.rpi4]\nselector = "board=rpi4"\n\n[tool.jumpstarter.client.rpi4.nodes]\n{nodes}',
        )

    MATCHING = f"""\
"dut.power" = "{POWER}"
"dut.storage" = "{FLASHER}"
"shell" = {{ client = "{SHELL}", methods = ["hello"] }}
"""

    def test_matching(self, workdir, leased, capsys):
        self.project(workdir, self.MATCHING + f'"camera" = {{ client = "{POWER}", required = false }}\n')
        assert main(["generate", "--check"]) == EXIT_OK
        out = capsys.readouterr().out
        assert "match the live exporter" in out
        assert "optional node camera" in out
        assert not (workdir / "client-rpi4.resource").exists()  # check never writes

    def test_drift(self, workdir, leased, capsys):
        nodes = f"""\
"dut.power" = "{SHELL}"
"dut.relay" = "{POWER}"
"shell" = {{ client = "{SHELL}", methods = ["bye"] }}
"""
        self.project(workdir, nodes)
        assert main(["generate", "--check", "--client", "rpi4"]) == EXIT_DRIFT
        out = capsys.readouterr().out
        assert f"changed class of dut.power: committed {SHELL}, live {POWER}" in out
        assert f"missing required node dut.relay ({POWER})" in out
        assert "changed shell methods of shell" in out
        assert f"new node dut.storage ({FLASHER})" in out
        assert "--capture --client rpi4" in out

    def test_check_from_describe(self, workdir, capsys):
        self.project(workdir, self.MATCHING)
        with serve(live_exporter()) as client:
            write(workdir / "describe.json", json.dumps({"driver_tree": describe_client(client)}))
        # a describe dump carries no shell methods, so they are not compared
        assert main(["generate", "--check", "--from", "describe.json"]) == EXIT_OK
