def write(path: Path, text: str) -> Path:
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(textwrap.dedent(text))
    return path


def run_suite(directory: Path, suite: str) -> tuple[int, dict[str, str]]:
    path = write(directory / "suite.robot", suite)
    output = directory / "output.xml"
    rc = robot.run(str(path), outputdir=str(directory), output=str(output), report="NONE", log="NONE", console="none")
    result = ExecutionResult(str(output))
    return rc, {t.name: t.status if t.status == "PASS" else f"{t.status}: {t.message}" for t in result.suite.tests}


def live_exporter() -> Composite:
    return Composite(
        children={
            "dut": Composite(children={"power": MockPower(), "storage": MockStorageMuxFlasher()}),
            "shell": Shell(methods={"hello": "echo hello $1 $GREETING"}),
        }
    )


