def write(path: Path, text: str) -> Path:
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(textwrap.dedent(text))
    return path


def run_suite(directory: Path, suite: str) -> tuple[int, dict[str, str]]:
    path = write(directory / "suite.robot", suite)
    output = directory / "output.xml"
    rc = robot.run(str(path), outputdir=str(directory), output=str(output), report="NONE", log="NONE", console="none")
    result = ExecutionResult(str(output))
    return rc, {t.name: t.status if t.status == "PASS" else f"{t.status}: {t.message}" for t in result.suite.tests}


@pytest.fixture
def workdir(tmp_path, monkeypatch):
    monkeypatch.chdir(tmp_path)
    for variable in (JUMPSTARTER_HOST, "JMP_LEASE", "JMP_EXPORTER", "JMP_EXPORTER_LABELS"):
        monkeypatch.delenv(variable, raising=False)
    write(tmp_path / "exporter.yaml", EXPORTER)
    yield tmp_path
    sessions.close_all()


class TestGenerateFromExporterConfig:
    def test_resource_text(self, workdir, capsys):
        assert main(["generate", "--exporter-config", "exporter.yaml"]) == EXIT_OK
        text = (workdir / "client.resource").read_text()
        lines = text.splitlines()
        assert lines[0] == "*** Settings ***"
        assert lines[1].startswith("Documentation    Generated by `jmp-robot generate` from ")
        assert "exporter config exporter.yaml (device MockRig, session default)" in lines[1]
        assert lines[2] == "Library    jumpstarter_robot.Jumpstarter    auto_import=False"
        assert lines[3] == (
            "Library    jumpstarter_robot.Session    default    exporter_config=${JMP_EXPORTER_CONFIG}    "
            "selector=${JMP_SELECTOR}    lease_name=${JMP_LEASE_NAME}    config=${JMP_CLIENT_CONFIG}    "
            "AS    session.default"
        )
        assert lines[4:7] == [
            f"Library    jumpstarter_robot.Driver    dut.power    client={POWER}    prefix=Dut Power    "
            + "session=default    AS    dut.power",
            f"Library    jumpstarter_robot.Driver    dut.storage    client={FLASHER}    prefix=Dut Storage    "
            + "session=default    AS    dut.storage",
            f"Library    jumpstarter_robot.Driver    shell    client={SHELL}    prefix=Shell    "
            + "session=default    methods=hello    AS    shell",
        ]
        assert text.endswith(
            "*** Variables ***\n"
            "${JMP_EXPORTER_CONFIG}    ${CURDIR}/exporter.yaml\n"
            "${JMP_SELECTOR}    ${EMPTY}\n"
            "${JMP_LEASE_NAME}    ${EMPTY}\n"
            "${JMP_CLIENT_CONFIG}    ${EMPTY}\n"
        )
        assert "default: wrote client.resource (3 driver libraries)\n" in capsys.readouterr().out

    def test_resource_runs_in_local_mode(self, workdir):
        assert main(["generate", "--exporter-config", "exporter.yaml"]) == EXIT_OK
        rc, statuses = run_suite(
            workdir,
            """\
            *** Settings ***
            Resource    client.resource

            *** Test Cases ***
            Power And Storage
                Dut Power On
                ${readings}=    Dut Power Read    max_items=2
                Length Should Be    ${readings}    2
                Dut Storage Dut
                Dut Power Off

            Shell Method
                ${result}=    Shell Hello    world    GREETING=hi
                Should Contain    ${result.stdout}    hello world hi

            Session Is Local
                ${name}=    Get Exporter Name
                Should Be Equal    ${name}    mock-rig
            """,
        )
        assert statuses == {"Power And Storage": "PASS", "Shell Method": "PASS", "Session Is Local": "PASS"}, statuses
        assert rc == 0


class TestProject:
    TOML = """\
    # project settings
    paths = ["tests"]

    [tool.jumpstarter.client]
    config = "lab"                # default client config

    [tool.jumpstarter.client.local]
    exporter-config = "exporter.yaml"
    resource = "client.resource"

    [tool.jumpstarter.client.local.aliases]
    "dut.power" = "Main Power"

    [tool.jumpstarter.client.rpi4]
    exporter-config = "exporter.yaml"
    selector = "board=rpi4"
    resource = "client-rpi4.resource"
    """

    @pytest.fixture
    def project(self, workdir):
        return write(workdir / "robot.toml", self.TOML)

    def test_regenerates_every_client(self, project, workdir):
        assert main(["generate"]) == EXIT_OK
        local = (workdir / "client.resource").read_text()
        rpi4 = (workdir / "client-rpi4.resource").read_text()
        assert "prefix=Main Power    session=local    AS    local.dut.power" in local
        assert "${JMP_LOCAL_CLIENT_CONFIG}    lab" in local
        assert "${JMP_RPI4_SELECTOR}    board=rpi4" in rpi4
        assert "AS    rpi4.dut.power" in rpi4
        # deterministic
        assert main(["generate"]) == EXIT_OK
        assert (workdir / "client.resource").read_text() == local
        assert (workdir / "client-rpi4.resource").read_text() == rpi4

    def test_unknown_client(self, project, capsys):
        assert main(["generate", "--client", "nope"]) == EXIT_ERROR
        assert "unknown client 'nope'" in capsys.readouterr().err
